"""Regenerate the example outputs in this folder.

Builds the test files, starts ``server.py`` over stdio, calls every tool the
way an MCP client does, and writes what came back:

``outputs/<name>.json``
    The result of each successful call.
``mcp_session.md``
    A readable transcript: the tool list, then each request and response,
    including the error messages returned for invalid requests.
``server.log``
    The server's log for the same session.

Usage::

    python examples/run_examples.py

Machine-specific paths in the saved files are replaced with short, stable ones
(``test_data/...``, ``./...``, ``<python-env>/...``).
"""
import asyncio
import json
import os
import sys
import tempfile
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

EXAMPLES_DIR = Path(__file__).resolve().parent
PROJECT_DIR = EXAMPLES_DIR.parent
sys.path.insert(0, str(PROJECT_DIR))

from make_test_data import make_test_data  # noqa: E402

# (output name, tool, arguments). The last three are expected to fail.
CALLS = [
    ("vcf_stats", "vcf_stats", {"path": "test.vcf"}),
    ("bam_stats", "bam_stats", {"path": "test.bam"}),
    ("bam_stats_region", "bam_stats", {"path": "test.bam", "region": "chr1:1001-1100"}),
    ("bam_qc", "bam_qc", {"path": "test.bam"}),
    ("h5ad_summary", "h5ad_summary", {"path": "small.h5ad", "column": "cell_type"}),
    ("h5ad_column_stats", "h5ad_column_stats", {"path": "small.h5ad", "column": "cell_type"}),
    ("fastq_stats", "fastq_stats", {"path": "sample_R1.fastq"}),
    ("fastq_stats_sampled", "fastq_stats", {"path": "sample_R1.fastq", "max_reads": 100}),
    ("fastq_quality_profile", "fastq_quality_profile", {"path": "sample_R1.fastq", "max_points": 26}),
    ("bam_depth_profile", "bam_depth_profile",
     {"path": "test.bam", "region": "chr1:1001-1100", "max_points": 10}),
    ("error_outside_folder", "vcf_stats", {"path": "/etc/passwd"}),
    ("error_wrong_contig", "bam_stats", {"path": "test.bam", "region": "1:1001-1100"}),
    ("error_unknown_column", "h5ad_summary", {"path": "small.h5ad", "column": "louvain"}),
]


async def run_session(data_dir: Path, log_file: Path):
    """Start the server, list its tools and make every call in CALLS."""
    params = StdioServerParameters(
        command=sys.executable,
        args=[str(PROJECT_DIR / "server.py")],
        cwd=str(PROJECT_DIR),
        env={**os.environ, "BIOFILE_ALLOWED_DIR": str(data_dir), "BIOFILE_LOG_FILE": str(log_file)},
    )
    # The server's stderr repeats what goes to the log file, so discard it here
    with open(os.devnull, "w") as quiet:
        async with stdio_client(params, errlog=quiet) as (read, write):
            async with ClientSession(read, write) as session:
                await session.initialize()
                tools = (await session.list_tools()).tools
                results = []
                for name, tool, args in CALLS:
                    result = await session.call_tool(tool, args)
                    results.append((name, tool, args, result.is_error, result.content[0].text))
                return tools, results


def write_transcript(tools, results, tidy, outputs: Path) -> str:
    """Save each successful result as JSON and return the Markdown transcript."""
    lines = [
        "# Example MCP session",
        "",
        "Generated by `python examples/run_examples.py`: an MCP client started",
        "`server.py` over stdio, listed the tools and called each one.",
        "",
        "## Tools offered by the server",
        "",
        "| Tool | Parameters | Read-only |",
        "|---|---|---|",
    ]
    for t in tools:
        params = ", ".join(f"`{p}`" for p in t.input_schema["properties"])
        lines.append(f"| `{t.name}` | {params} | {t.annotations.read_only_hint} |")

    lines += ["", "## Calls", ""]
    for name, tool, args, is_error, text in results:
        text = tidy(text)
        if is_error:
            body, lang = text, "text"
        else:
            body, lang = json.dumps(json.loads(text), indent=2), "json"
            (outputs / f"{name}.json").write_text(body + "\n")

        call = ", ".join(f"{k}={v!r}" for k, v in args.items())
        lines += [
            f"### `{tool}({call})`",
            "",
            "Error returned to the client:" if is_error else "Result:",
            "",
            f"```{lang}",
            body,
            "```",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        data_dir = make_test_data(Path(tmp) / "test_data").resolve()
        log_file = Path(tmp) / "server.log"

        tools, results = asyncio.run(run_session(data_dir, log_file))

        replacements = [
            (str(data_dir), "test_data"),
            (str(PROJECT_DIR), "."),
            (str(Path(sys.prefix).resolve()), "<python-env>"),
            (sys.prefix, "<python-env>"),
        ]

        def tidy(text: str) -> str:
            for old, new in replacements:
                text = text.replace(old, new)
            return text

        outputs = EXAMPLES_DIR / "outputs"
        outputs.mkdir(exist_ok=True)

        transcript = write_transcript(tools, results, tidy, outputs)
        (EXAMPLES_DIR / "mcp_session.md").write_text(transcript)
        (EXAMPLES_DIR / "server.log").write_text(tidy(log_file.read_text()))

    print("Wrote examples/outputs/, examples/mcp_session.md and examples/server.log")


if __name__ == "__main__":
    main()
